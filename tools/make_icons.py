"""
Turns the chosen logo (logo_source/quintess-logo-source.png, generated by
tools/make_logo.py) into the program's icons and the website's images.

    python tools/make_icons.py

The mark (the page-shaped Q with its pen nib) is lifted off the generated
tile and redrawn on a clean tile of exact color and corner radius, centered,
so every size is consistent. Writes:

    assets/quintess.png        1024 px app icon
    assets/quintess-256.png    the window icon
    assets/quintess.ico        16 to 256 px, for the programs and installer
    assets/quintess-mark.png   the mark alone on transparency (the wordmark)

Requires Pillow and numpy.
"""
import pathlib

import numpy as np
from PIL import Image, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "logo_source" / "quintess-logo-source.png"
ASSETS = ROOT / "assets"

TILE_COLOR = (11, 11, 16)  # #0B0B10, the Studio theme's darkest ink
CORNER_RADIUS_FRACTION = 0.225
MARK_FRACTION = 0.66  # the mark's larger side, as a share of the tile


def lift_mark(source: Image.Image) -> Image.Image:
    """The mark on transparency: each pixel is unmixed from the tile color,
    so anti-aliased edges keep their partial coverage."""
    pixels = np.asarray(source.convert("RGB")).astype(np.float64)
    height, width, _ = pixels.shape
    # The tile's own color, measured where only tile shows (left middle).
    tile = np.median(pixels[height // 2 - 40:height // 2 + 40, 40:120].reshape(-1, 3), axis=0)
    # Ignore the tile's rim, where the white page background shows through.
    inset = int(width * 0.08)
    region = pixels[inset:height - inset, inset:width - inset]
    difference = region - tile
    alpha = np.clip(np.max(np.abs(difference) / np.maximum(255.0 - tile, tile), axis=2), 0.0, 1.0)
    # Faint noise in the generated tile is not part of the mark.
    alpha = np.clip((alpha - 0.06) / 0.94, 0.0, 1.0)
    color = tile + difference / np.maximum(alpha[..., None], 1e-6)
    rgba = np.dstack([np.clip(color, 0, 255), alpha * 255.0]).astype(np.uint8)
    mark = Image.fromarray(rgba, "RGBA")
    return mark.crop(mark.getchannel("A").point(lambda value: 255 if value > 24 else 0).getbbox())


def rounded_tile(size: int) -> Image.Image:
    """A tile with anti-aliased corners (drawn four times larger, then shrunk)."""
    scale = 4
    big = Image.new("RGBA", (size * scale, size * scale), (0, 0, 0, 0))
    ImageDraw.Draw(big).rounded_rectangle([0, 0, size * scale - 1, size * scale - 1], radius=int(size * scale * CORNER_RADIUS_FRACTION), fill=TILE_COLOR + (255,))
    return big.resize((size, size), Image.LANCZOS)


def icon(mark: Image.Image, size: int) -> Image.Image:
    tile = rounded_tile(size)
    longest = max(mark.size)
    scale = size * MARK_FRACTION / longest
    shrunk = mark.resize((max(1, round(mark.width * scale)), max(1, round(mark.height * scale))), Image.LANCZOS)
    tile.alpha_composite(shrunk, ((size - shrunk.width) // 2, (size - shrunk.height) // 2))
    return tile


def main() -> None:
    mark = lift_mark(Image.open(SOURCE))
    mark_out = mark.copy()
    mark_out.thumbnail((512, 512), Image.LANCZOS)
    mark_out.save(ASSETS / "quintess-mark.png")
    full = icon(mark, 1024)
    full.save(ASSETS / "quintess.png")
    icon(mark, 256).save(ASSETS / "quintess-256.png")
    # Each icon size is drawn from the full-size mark rather than shrunk from
    # the 1024 px icon, which keeps small sizes sharper.
    sizes = [16, 20, 24, 32, 40, 48, 64, 128, 256]
    images = [icon(mark, size) for size in sizes]
    images[-1].save(ASSETS / "quintess.ico", sizes=[(s, s) for s in sizes], append_images=images[:-1])
    print("wrote icons from", SOURCE.name, "mark size", mark.size)


if __name__ == "__main__":
    main()
